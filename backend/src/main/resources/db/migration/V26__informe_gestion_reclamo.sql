CREATE TABLE informe_gestion_reclamo (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    periodo_inicio DATE NOT NULL,
    periodo_fin DATE NOT NULL,
    responsable VARCHAR(80),
    cargo VARCHAR(80),
    aprobado_por VARCHAR(80),
    causas_recurrentes VARCHAR(1000),
    areas_frecuencia VARCHAR(1000),
    efectividad VARCHAR(1000),
    conclusiones VARCHAR(2000),
    comercial_nombre VARCHAR(80),
    comercial_fecha DATE,
    gerencia_nombre VARCHAR(80),
    gerencia_fecha DATE,
    CONSTRAINT uq_informe_gestion_periodo UNIQUE (periodo_inicio, periodo_fin),
    CONSTRAINT chk_informe_gestion_periodo CHECK (periodo_fin >= periodo_inicio)
);
